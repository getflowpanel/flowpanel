import { rehypeCodeDefaultOptions } from "fumadocs-core/mdx-plugins";
import {
  defineCollections,
  defineConfig,
  defineDocs,
  frontmatterSchema,
  remarkInclude,
} from "fumadocs-mdx/config";
import { transformerTwoslash } from "fumadocs-twoslash";
import { z } from "zod";
import { DOC_KINDS } from "./src/shared/lib/docs-contract";

const docsFrontmatterSchema = frontmatterSchema.extend({
  kind: z.enum(DOC_KINDS),
  metaTitle: z.string().optional(),
});

export const docs = defineDocs({
  dir: "content/docs",
  docs: {
    schema: docsFrontmatterSchema,
  },
});

export const blog = defineCollections({
  type: "doc",
  dir: "content/blog",
  schema: z.object({
    title: z.string(),
    description: z.string(),
    date: z.coerce.date(),
    authors: z.array(z.string()).min(1),
    tags: z.array(z.string()).default([]),
    cover: z.string().optional(),
  }),
});

export const examples = defineCollections({
  type: "doc",
  dir: "content/examples",
  schema: z.object({
    title: z.string(),
    description: z.string(),
    repo: z.string().url(),
    stack: z.array(z.string()),
    cover: z.string().optional(),
  }),
});

// Generated by scripts/aggregate-changelog.mjs.
export const changelog = defineCollections({
  type: "doc",
  dir: "content/changelog",
  schema: z.object({
    title: z.string(),
    description: z.string(),
  }),
});

export default defineConfig({
  mdxOptions: {
    remarkPlugins: [remarkInclude],
    // ```ts twoslash blocks are type-checked at build time.
    rehypeCodeOptions: {
      // Spread the defaults: a bare transformers array would replace Fumadocs' own via a shallow merge.
      ...rehypeCodeDefaultOptions,
      transformers: [...(rehypeCodeDefaultOptions.transformers ?? []), transformerTwoslash()],
    },
  },
});
